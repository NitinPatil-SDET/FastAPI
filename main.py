from fastapi import FastAPI, Query, HTTPException, Path
import json


app = FastAPI()

@app.get("/")
def hey():
    return {'message':'hey this first API'}

@app.get('/about')
def about():
    return {'Message':'This is Nitin Learning FastAPI'}

#helper function to load data from json
def load_data():
    with open('patients.json', 'r') as f:
        data=json.load(f)

    return data

#Get complet data from the JSON
@app.get('/view')
def view():
    data = load_data()
    return data

#Get particular data from the JSON basic on the path parameter
@app.get('/patient/{patient_id}')
def view_patient(patient_id:str = Path(..., descripation='ID of the patient in DB',examples='P001')):
    data = load_data()

    if patient_id in data:
        return data[patient_id]
    #return {'error':'patient not found!!!'} 
    raise HTTPException(status_code=404, detail='patient not found!!!')


#Create new end point to demostrate quri parameter
@app.get('/sort')
def sort_patients(sort_by: str = Query(..., description='Sort on the basic of height, weight, age or bmi'), 
                  order_by:str=Query('asc',description='Sort in Asceding and desecnding order')):

    valid_fields=['height','weight','bmi', 'age']

    if sort_by not in valid_fields:
        raise HTTPException(status_code=400, 
                            detail=f'Invalid fields, Please select from{valid_fields}')

    if order_by not in ['asc', 'desc']:
        raise HTTPException(status_code=400, 
                            detail='Invalid order please select asc and desc')

    data = load_data()

    sort_order = True if order_by=='desc' else False
    sorted_data = sorted(data.values(), key=lambda x:x.get(sort_by, 0), reverse=sort_order) 

    return sorted_data







































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































